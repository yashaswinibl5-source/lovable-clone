package com.pm.lovable_clone.service;


import org.springframework.stereotype.Service;
import org.springframework.web.servlet.mvc.method.annotation.SseEmitter;

import java.io.IOException;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;

@Service
public class MockAiCodeGeneratorService implements AiCodeGeneratorService {

    private final ExecutorService executor = Executors.newCachedThreadPool();

    @Override
    public void streamAppGeneration(String prompt, SseEmitter emitter) {
        executor.execute(() -> {
            try {
                // Realistic multi-file response generated by "AI"
                String mockAiOutput = getMockProjectForPrompt(prompt);

                // Stream character-by-character / word-by-word
                String[] tokens = mockAiOutput.split("(?<=\\s)|(?<=\\n)");
                for (String token : tokens) {
                    emitter.send(SseEmitter.event()
                            .name("chunk")
                            .data(token));
                    Thread.sleep(25); // Simulate LLM typing speed
                }

                // Send completion signal
                emitter.send(SseEmitter.event().name("done").data("[DONE]"));
                emitter.complete();

            } catch (IOException | InterruptedException e) {
                emitter.completeWithError(e);
            }
        });
    }

    private String getMockProjectForPrompt(String prompt) {
        return """
            I am generating a modern web application based on your prompt: "%s"

            <boltAction type="file" filePath="src/App.tsx">
            import React, { useState } from 'react';
            import { Sparkles, Plus, Trash2 } from 'lucide-react';

            export default function App() {
              const [items, setItems] = useState<string[]>(['Explore Lovable clone', 'Build with Spring Boot']);
              const [input, setInput] = useState('');

              const addItem = () => {
                if (!input.trim()) return;
                setItems([...items, input.trim()]);
                setInput('');
              };

              return (
                <div className="min-h-screen bg-slate-900 text-white flex flex-col items-center p-8 font-sans">
                  <header className="flex items-center gap-2 mb-8">
                    <Sparkles className="text-amber-400 w-8 h-8" />
                    <h1 className="text-3xl font-extrabold tracking-tight">AI Generated Workspace</h1>
                  </header>

                  <main className="w-full max-w-md bg-slate-800/60 p-6 rounded-2xl shadow-xl border border-slate-700">
                    <div className="flex gap-2 mb-4">
                      <input
                        type="text"
                        value={input}
                        onChange={(e) => setInput(e.target.value)}
                        placeholder="Add a new task..."
                        className="flex-1 bg-slate-700 text-white px-4 py-2 rounded-lg outline-none focus:ring-2 focus:ring-indigo-500"
                      />
                      <button
                        onClick={addItem}
                        className="bg-indigo-600 hover:bg-indigo-500 px-4 py-2 rounded-lg font-medium flex items-center gap-1 transition"
                      >
                        <Plus size={18} /> Add
                      </button>
                    </div>

                    <ul className="space-y-2">
                      {items.map((item, idx) => (
                        <li key={idx} className="flex justify-between items-center bg-slate-700/40 px-4 py-2 rounded-lg border border-slate-600">
                          <span>{item}</span>
                          <button
                            onClick={() => setItems(items.filter((_, i) => i !== idx))}
                            className="text-slate-400 hover:text-red-400 transition"
                          >
                            <Trash2 size={16} />
                          </button>
                        </li>
                      ))}
                    </ul>
                  </main>
                </div>
              );
            }
            </boltAction>

            <boltAction type="file" filePath="package.json">
            {
              "name": "ai-generated-app",
              "private": true,
              "version": "0.0.0",
              "type": "module",
              "scripts": {
                "dev": "vite",
                "build": "tsc && vite build"
              },
              "dependencies": {
                "react": "^18.3.1",
                "react-dom": "^18.3.1",
                "lucide-react": "^0.344.0"
              }
            }
            </boltAction>
            """.formatted(prompt);
    }
}